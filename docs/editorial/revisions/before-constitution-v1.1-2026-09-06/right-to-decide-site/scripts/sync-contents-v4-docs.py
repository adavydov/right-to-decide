SNAP = PACK / 'revisions/pre-contents-v4.0-2026-09-05'
records = []

def read(p):
    return p.read_text(encoding='utf-8-sig')

def preserve(p):
    if not p.exists():
        return
    relative = p.relative_to(ROOT) if p.is_relative_to(ROOT) else Path('workspace') / p.relative_to(WORKSPACE)
    target = SNAP / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists():
        target.write_bytes(p.read_bytes())
    records.append({'source': relative.as_posix(), 'snapshot': target.relative_to(SNAP).as_posix(), 'sha256': hashlib.sha256(target.read_bytes()).hexdigest()})

def write(p, value):
    preserve(p)
    p.write_text(value.rstrip() + '\n', encoding='utf-8', newline='\n')

