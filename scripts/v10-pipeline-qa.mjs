import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE);
const base = process.env.SITE_URL || 'http://127.0.0.1:3220/right-to-decide';
const out = 'docs/research/v10-pipeline';
fs.mkdirSync(out+'/screenshots',{recursive:true});
const corpus=JSON.parse(fs.readFileSync('public/editorial/corpus.json','utf8'));
const edition=corpus.editions.find(e=>e.id==='literary-manuscript-v9.0-26472e4aa686');
const chapter=edition.chapters.find(c=>c.id==='chapter-01');
const block=chapter.blocks.find(b=>b.type==='paragraph'&&b.selection_supported);
const seed={id:'v10-pipeline-technical-note',created_at:'2026-09-12T15:00:00.000Z',message:'Техническая проверка исходной редакции',quote:block.text,target:{scope:'block',book_id:corpus.book_id,edition_id:edition.id,chapter_id:chapter.id,block_id:block.id,block_snapshot_sha256:block.snapshot_sha256,normalization:'oe-text-v1'}};
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const report={at:new Date().toISOString(),activeEdition:corpus.current_edition_id,archiveEdition:edition.id,checks:[],requests:[],errors:[]};
page.on('pageerror',e=>report.errors.push(e.message));
page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))report.requests.push({method:r.method(),url:r.url()});});
try {
  await page.goto(base+'/editions/v9/',{waitUntil:'networkidle'});
  assert.equal(await page.getByRole('heading',{name:'Редакция 9.0',exact:true}).count(),1);
  assert.equal(await page.locator('.preview-row').count(),22);
  for(const width of [1440,390]) {
    await page.setViewportSize({width,height:width===390?844:1000});
    await page.goto(base+'/editions/v9/',{waitUntil:'networkidle'});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:`${out}/screenshots/archive-index-${width}.png`});
    await page.goto(base+'/editions/v9/read/chapter-01/',{waitUntil:'networkidle'});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:`${out}/screenshots/archive-reader-${width}.png`});
  }
  report.checks.push('Archive index and real reader render at 1440/390 without horizontal overflow');
  await page.evaluate(note=>localStorage.setItem('right-to-decide:open-editorial:browser-notes:v1',JSON.stringify([note])),seed);
  await page.goto(base+'/open-editorial/me/',{waitUntil:'networkidle'});
  const original=page.getByRole('link',{name:'Открыть исходный текст этой заметки ↗'});
  await original.waitFor();
  assert.ok((await original.getAttribute('href')).includes('/editions/v9/read/chapter-01/#'+block.dom_id));
  await page.screenshot({path:`${out}/screenshots/original-note-390.png`});
  await original.click();await page.waitForLoadState('networkidle');
  assert.ok(page.url().includes('/editions/v9/read/chapter-01/'));
  const text=await page.locator(`[id="${block.dom_id}"]`).innerText();
  assert.equal(text.replace(/\s+/g,' ').trim(),block.text.replace(/\s+/g,' ').trim());
  assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('right-to-decide:open-editorial:browser-notes:v1'))),[seed]);
  report.checks.push('Old note resolves exact edition/chapter/block and keeps every original stored field unchanged');
  await page.getByTestId('reader-toolbar').getByRole('button',{name:'Содержание',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'Содержание',exact:true});
  assert.ok((await panel.getByRole('link').first().getAttribute('href')).includes('/editions/v9/read/'));
  await page.keyboard.press('Escape');
  report.checks.push('Reader contents/navigation stay within archive edition');
  const detail=page.locator('details').filter({hasText:'Личная заметка или черновик замечания'});
  await detail.locator('summary').click();
  await detail.getByLabel('Личная заметка',{exact:true}).fill('Техническая запись из архива');
  await detail.getByRole('button',{name:'Сохранить только в этом браузере',exact:true}).click();
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('right-to-decide:open-editorial:browser-notes:v1')));
  assert.equal(saved[0].target.edition_id,edition.id);
  assert.deepEqual(saved[1],seed);
  report.checks.push('New note made in archive binds to edition 9.0, without editing prior note');
  assert.deepEqual(report.requests,[]);assert.deepEqual(report.errors,[]);
  report.status='PASS';
} finally {await browser.close();fs.writeFileSync(out+'/browser-qa.json',JSON.stringify(report,null,2)+'\n');}
console.log(JSON.stringify(report,null,2));
