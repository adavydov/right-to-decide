def read_json(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def norm(text):
    return " ".join(text.split())

def sentence(value, field):
    if isinstance(value, dict):
        return " ".join(value[key] for key in ("change", "evidence_limit") if value.get(key))
    if value == "not_observed":
        return ("Изменение способности в этом эпизоде не показано." if field == "capability"
                else "Изменение порядка работы в этом эпизоде не показано.")
    value = re.sub(r"^(reported_by_author|not_observed):\s*", "", value)
    return value[:1].upper() + value[1:]

def source_link(entry):
    number = entry["id"]
    if number == 1:
        return []
    # Only selected descriptive source pages; no file mirrors or private-share URLs.
    candidates = entry["source_urls"]
    selected = entry["acquisition_url"]
    if number == 23:
        selected = candidates[0]
    if number == 30:
        selected = candidates[0]
    if number == 38:
        return [{"label": "Студенты · Викитека", "url": candidates[0], "kind": "text"},
                {"label": "Инженеры · Викитека", "url": candidates[1], "kind": "text"}]
    kind = ("text" if entry["status"] == "full_text_downloaded" else
            "excerpt" if number in (36, 47) else
            "archive" if number in (11, 15, 42) else
            "catalog" if number in (6, 19, 20, 23, 30) else "publisher")
    labels = {"text": "Электронная публикация", "excerpt": "Доступный фрагмент",
              "archive": "Архив и каталог", "catalog": "Библиографическая запись",
              "publisher": "Об издании"}
    if number == 2:
        return [{"label": "Другая электронная публикация", "url": selected, "kind": "text",
                 "note": "Ссылка из библиографического реестра. Её тождество использованному FB2 1989 года не установлено; цитаты сверены по предоставленному экземпляру."}]
    return [{"label": labels[kind], "url": selected, "kind": kind}]

