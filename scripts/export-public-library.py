    for section in coverage["main_text_readers"]:
        assert sha(corpus / section["reading_report"]) == section["reading_report_sha256"], "Reading report mismatch"
        assert sha(corpus / section["cards_file"]) == section["cards_file_sha256"], "Reading card version mismatch"
    paragraphs = {p["id"]: p for p in
                  (json.loads(line) for line in (grabin / "extracted/paragraphs.jsonl").read_text(encoding="utf-8-sig").splitlines())}
    verified = []
    quote_count = 0
    input_cards = []
    for part in review["parts"]:
        filename = part["cards_file_name"]
        actual = sha(grabin / "cards" / filename)
        assert actual == CARD_HASHES[filename] == part["cards_file_sha256"], filename
        assert part["status"] == "context_reviewed" and part["open_material_findings"] == 0
        assert sha(corpus / part["report"]) == part["report_sha256"], "Context report mismatch"
        data = read_json(grabin / "cards" / filename)
        batch = data["cards"] if isinstance(data, dict) else data
        assert [c["id"] for c in batch] == part["card_ids"]
        for card in batch:
            assert card["source_sha256"] == SOURCE_SHA
            assert all(pid in paragraphs for pid in card["source_paragraph_ids"])
            for q in card["quotes"]:
                assert set(q["paragraph_ids"]).issubset(card["source_paragraph_ids"])
                text = " ".join(paragraphs[pid]["text"] for pid in q["paragraph_ids"])
                assert norm(q["text"]) in norm(text), (card["id"], q["paragraph_ids"])
