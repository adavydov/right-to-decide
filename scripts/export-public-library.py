def attribution(card, quote):
    cid = card["id"]
    pids = set(quote["paragraph_ids"])
    if cid == "GRABIN1989-P3-C01":
        return "Ф. Ф. Калеганов, воспоминания, включённые В. Г. Грабиным"
    if cid == "GRABIN1989-P3-C02":
        return ("В. Г. Грабин, реплика в воспоминаниях Ф. Ф. Калеганова; точность реплики самим Калегановым не гарантируется"
                if "GRABIN1989:P02909" in pids else
                "Ф. Ф. Калеганов, собственная реплика по памяти; дословность диалога не гарантируется")
    if cid == "GRABIN1989-P1-C02" and "GRABIN1989:P00223" in pids:
        return "Руководители дипломного проектирования, их решение в изложении В. Г. Грабина"
    if cid == "GRABIN1989-C2-07" and "GRABIN1989:P02171" in pids:
        return "В. Г. Грабин цитирует полученное сообщение; архивный оригинал не сопоставлялся"
    return "В. Г. Грабин"

def card_record(card):
    cid = card["id"]
    sections = card["source_section"]
    if isinstance(sections, str):
        sections = [s.strip() for s in sections.split(";") if "локаторы FB2" not in s]
    interpretation = INTERPRETATIONS.get(cid, card["interpretation"])
    interpretation = re.sub(r"^(Наш вывод|Наша интерпретация|Наше чтение):\s*", "", interpretation)
    interpretation = interpretation[:1].upper() + interpretation[1:]
    context = card["context"]
    if cid == "GRABIN1989-C2-07":
        context = context.replace("Это разные события, их нельзя сливать в одну сцену.", "Это разные события.")
    title = card["title"]
    if cid == "GRABIN1989-P3-C01":
        title = "Возможность задать вопрос: как новичок учится у технолога"
    tags = [tag.replace("_", " ").replace("-", " ") for tag in card["tags"]
            if tag not in ("история-до-тезиса",)]
    return {
        "id": cid, "sourceId": "source-02", "title": title,
        "topics": [TOPICS[key] for key in TOPIC_KEYS[cid]], "tags": tags,
        "sections": sections, "paragraphIds": card["source_paragraph_ids"],
        "context": context, "observation": card["observation"], "interpretation": interpretation,
        "quotes": [{"text": q["text"], "attribution": attribution(card, q),
                    "paragraphIds": q["paragraph_ids"]} for q in card["quotes"]],
        "capability": sentence(card["observed_change_in_capability"], "capability"),
        "workProcedure": sentence(card["change_in_work_procedure"], "procedure"),
        "limits": LIMITS[cid],
        "review": {"date": AS_OF, "sourceCorrespondence": "checked",
                   "historicalCorroboration": "not-established",
                   "note": "Цитаты и контекст сверены с использованным FB2. Проверка соответствия мемуарам не устанавливает историческую достоверность событий по независимым документам."},
    }

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, default=SITE.parent / "book-memory")
    parser.add_argument("--audit", type=Path, default=SITE.parent / "docs/research/publication-2026-09-05/library-export-audit.json")
    args = parser.parse_args()
    corpus = args.corpus.resolve()
    grabin = corpus / "books/grabin-oruzhie-pobedy-1989"
    registry = read_json(corpus / "acquisition/library-registry.json")
    assert registry["as_of"] == AS_OF
    entries = registry["entries"]
    assert sorted(e["id"] for e in entries) == list(range(1, 49))
    original_paths = list((grabin / "source").glob("*.fb2"))
